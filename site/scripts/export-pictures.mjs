#!/usr/bin/env node
// Exports the website's picture library to the app, so both show the same
// drawings with the same names:
//
//   assets/images/pictures/<id>.webp     rendered from pictureSvg() by resvg,
//                                          stored as lossless WebP (Pillow)
//   assets/images/pictures/manifest.json  id + hash of the SVG each image came from
//   lib/features/gentle_activities/data/picture_library.g.dart
//                                          the list and every translated name
//
// Run from site/ after changing a picture or a picture name:
//   node --experimental-strip-types scripts/export-pictures.mjs   (Node 22)
//   node scripts/export-pictures.mjs                              (Node 24)
// Needs Python 3 with Pillow for the WebP step (as scripts/make-images.py).
// site/src/data/pictures.test.ts fails when the exports are out of date.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';
import { PICTURES, pictureSvg } from '../src/data/pictures.ts';

const SITE = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(SITE, '..');
const OUT = join(REPO, 'assets/images/pictures');
const DART = join(REPO, 'lib/features/gentle_activities/data/picture_library.g.dart');
const PLAY = join(SITE, 'src/i18n/play');
/** Pixels per side: sharp on a phone tile and on Look together. */
const SIZE = 720;

export const svgHash = (svg) => createHash('sha256').update(svg).digest('hex').slice(0, 16);

mkdirSync(OUT, { recursive: true });
const keep = new Set(PICTURES.map((p) => `${p.id}.webp`));
for (const file of readdirSync(OUT)) {
  if (/\.(png|webp)$/.test(file) && !keep.has(file)) rmSync(join(OUT, file));
}

const work = mkdtempSync(join(tmpdir(), 'gm-pictures-'));
const manifest = [];
for (const picture of PICTURES) {
  const svg = pictureSvg(picture);
  const png = new Resvg(svg, { fitTo: { mode: 'width', value: SIZE } }).render().asPng();
  writeFileSync(join(work, `${picture.id}.png`), png);
  manifest.push({ id: picture.id, category: picture.category, svg: svgHash(svg) });
}
// Lossless, so the app shows exactly what resvg drew, at about a third of the size.
execFileSync('python3', ['-c', [
  'import sys, pathlib',
  'from PIL import Image',
  'src, out = map(pathlib.Path, sys.argv[1:])',
  'for p in sorted(src.glob("*.png")):',
  '    Image.open(p).convert("RGB").save(out / (p.stem + ".webp"), "WEBP", lossless=True, method=6)',
].join('\n'), work, OUT]);
rmSync(work, { recursive: true, force: true });
writeFileSync(join(OUT, 'manifest.json'), `${JSON.stringify({ size: SIZE, pictures: manifest }, null, 2)}\n`);

// Names: English from pictures.ts, the rest from the site's play files.
// Site codes use a hyphen (pt-BR); the app's locale names use an underscore.
const ids = new Set(PICTURES.map((p) => p.id));
const names = { en: Object.fromEntries(PICTURES.map((p) => [p.id, p.name])) };
for (const file of readdirSync(PLAY).filter((f) => f.endsWith('.json')).sort()) {
  const code = file.slice(0, -5);
  if (code === 'en') continue;
  const pictures = JSON.parse(readFileSync(join(PLAY, file), 'utf8')).pictures ?? {};
  const own = Object.entries(pictures).filter(([id, name]) => ids.has(id) && typeof name === 'string' && name.trim());
  if (own.length) names[code.replace('-', '_')] = Object.fromEntries(own);
}

const q = (s) => `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$')}'`;
const dart = [
  '// GENERATED by site/scripts/export-pictures.mjs from site/src/data/pictures.ts',
  '// and site/src/i18n/play/*.json. Do not edit; run the script instead.',
  '// dart format off',
  '// coverage:ignore-file',
  "import 'package:golden_moments/features/gentle_activities/models/activity_picture.dart';",
  '',
  '/// The drawings shared with the website, in the website\'s order.',
  'const pictureLibrary = <ActivityPicture>[',
  ...PICTURES.map((p) => `  ActivityPicture(id: ${q(p.id)}, label: ${q(p.name)}, asset: ${q(`assets/images/pictures/${p.id}.webp`)}),`),
  '];',
  '',
  '/// Picture names by app locale name (en, pt_BR, zh_Hans). A language that',
  '/// lacks a name falls back to its base language, then to English.',
  'const pictureNames = <String, Map<String, String>>{',
  ...Object.entries(names).map(([code, map]) =>
    `  ${q(code)}: {${Object.entries(map).map(([id, name]) => `${q(id)}: ${q(name)}`).join(', ')}},`),
  '};',
  '',
].join('\n');
writeFileSync(DART, dart);
console.log(`Exported ${PICTURES.length} pictures at ${SIZE}px; names in ${Object.keys(names).length} languages.`);
